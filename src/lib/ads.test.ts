import {canShowAlightingAd,findMatchingLandmarkAd,getVisiblePinAds,isDeliverableAd,type AdCampaign} from './ads.ts';
import type {Option,Point} from './router.ts';
import type {RouteStop} from './navigation.ts';

const at:Point={lat:21.5,lng:-104.9};
const near:Point={lat:21.5005,lng:-104.9};
const far:Point={lat:21.55,lng:-104.9};
const today=new Date(2026,9,11,12);
const base:AdCampaign={id:'base',clientId:'client',type:'landmark',title:'Tienda',description:'',icon:'★',referenceText:'Tienda',coordinates:near,radiusMeters:100,isActive:true,createdAt:'2026-10-01'};
const expect=(value:unknown,message:string)=>{if(!value)throw new Error(message)};
expect(isDeliverableAd({...base,startDate:'2026-10-11',endDate:'2026-10-11'},today),'Both campaign date boundaries are inclusive');
expect(!isDeliverableAd({...base,startDate:'2026-10-12'},today),'Future campaign must not render');
expect(!isDeliverableAd({...base,endDate:'2026-10-10'},today),'Expired campaign must not render');
expect(!isDeliverableAd({...base,startDate:'not-a-date'},today),'Invalid campaign date fails closed');
expect(!isDeliverableAd({...base,isActive:false},today),'Paused campaign must not render');
expect(!isDeliverableAd({...base,coordinates:{lat:NaN,lng:-104.9}},today),'Invalid coordinates fail closed');
expect(!isDeliverableAd({...base,radiusMeters:-1},today),'Invalid radius fails closed');
expect(!isDeliverableAd({...base,routeIds:['otra']},today,['mexico']),'Wrong route must not render');
expect(isDeliverableAd({...base,routeIds:['mexico']},today,['mexico']),'Matching route may render');
expect(findMatchingLandmarkAd(at,[{...base,id:'far',coordinates:far},base],'mexico',today)?.id==='base','Only nearby landmark can be selected');
expect(!findMatchingLandmarkAd(at,[{...base,routeIds:['otra']}],'mexico',today),'Landmark route filter applies');
expect(!findMatchingLandmarkAd(at,[{...base,referenceText:''}],'mexico',today),'Landmark requires reference text');
expect(!canShowAlightingAd('walk',true,800,1000,200),'Walking never shows alighting ad');
expect(!canShowAlightingAd('bus',false,800,1000,200),'Untrusted GPS never shows alighting ad');
expect(!canShowAlightingAd('bus',true,500,1000,500),'No ad before alighting window');
expect(canShowAlightingAd('bus',true,700,1000,300),'Trusted bus progress inside window shows ad');
const option:Option={id:'trip',minutes:5,walk:0,transfers:0,fare:10,score:5,legs:[{kind:'bus',from:at,to:{lat:21.51,lng:-104.9},geometry:[at,{lat:21.51,lng:-104.9}],minutes:5,meters:1100,route:{id:'mexico',name:'México',color:'#f00',groupName:'México',coordinates:[at,{lat:21.51,lng:-104.9}]}}]};
const pin:AdCampaign={...base,id:'pin',type:'pin',routeIds:['mexico']};
expect(getVisiblePinAds([pin],option,[],today).length===1,'Pin near selected route appears');
expect(getVisiblePinAds([{...pin,routeIds:['otra']}],option,[],today).length===0,'Pin for another route stays hidden');
expect(getVisiblePinAds([{...pin,coordinates:far}],option,[],today).length===0,'Distant pin stays hidden');
const stop:RouteStop={id:'stop',name:'Parada',coordinates:near,legIndex:0,along:55,distance:0,inferred:false,side:'right'};
expect(getVisiblePinAds([pin],option,[stop],today).length===0,'Stop wins close visual collision');
expect(getVisiblePinAds([pin],undefined,[],today).length===0,'Route-targeted pin waits for matching trip');
console.log('OK: ad dates, activation, route targeting, proximity and stop collision');
