import {meters,type Point} from './router.ts';
import {reliableProgressSample,updateProgress,type ProgressState} from './progressGuard.ts';
import {alightingStage,journeyStatus,type JourneyFix} from './journeyStatus.ts';
import {appendReportFix,saveRouteReport,routeReportGeoJSON,type RouteReport} from './routeReport.ts';
import {setLocalRecordPreference} from './localRecords.ts';
import {isDeliverableAd,type AdCampaign} from './ads.ts';
import {sponsoredIntroTiming} from './sponsoredTrip.ts';
import ads from '../../public/data/ads.json' with {type:'json'};
function expect(value:unknown,message:string){if(!value)throw new Error(message)}
const origin={lat:21.5,lng:-104.9},point=(x:number,y=0):Point=>({lat:origin.lat+y/111320,lng:origin.lng+x/(111320*Math.cos(origin.lat*Math.PI/180))});
const line=[point(0),point(3000)];
let state:ProgressState={along:0};
for(const [x,time] of [[700,1000],[720,2000],[740,3000],[760,4000]])state=updateProgress(state,reliableProgressSample(point(x),line,30,time),'bus');
expect(state.along>750,'Boarding more than 150 m into the leg must initialize and keep advancing');
const before=state.along;
state=updateProgress(state,null,'bus');
expect(state.along===before,'An imprecise/off-route reading preserves confirmed progress');
state=updateProgress(state,reliableProgressSample(point(780),line,15,35000),'bus');
expect(state.along===before,'Signal recovery still requires two fixes');
state=updateProgress(state,reliableProgressSample(point(800),line,15,36000),'bus');
expect(state.along>790,'GPS recovery resumes distance updates');
const jump=updateProgress(state,reliableProgressSample(point(2700),line,5,37000),'bus');
expect(jump.along===state.along,'A sudden forward jump must not trim the route or signal arrival');
const fixes=(positions:number[][]):JourneyFix[]=>positions.map(([x,y,t])=>({point:point(x,y),accuracy:8,time:t}));
const off=fixes([[100,200,1000],[130,210,8000],[160,210,17000]]);
expect(journeyStatus(off,line,'bus',17000).kind==='off-route','Sustained 100+ m deviation should notify');
expect(journeyStatus(off.slice(0,1),line,'bus',1000).kind==='tracking','One GPS outlier must not notify');
expect(journeyStatus(fixes([[700,0,1000],[610,0,8000],[500,0,17000]]),line,'bus',17000).kind==='wrong-direction','A sustained reverse traversal of the same avenue needs a different itinerary');
const stopped=fixes(Array.from({length:7},(_,i)=>[100+i%2,0,1000+i*10000]));
expect(journeyStatus(stopped,line,'bus',61000).kind==='stopped','Fresh stable readings establish a stopped bus');
expect(journeyStatus(stopped,line,'bus',90000).kind==='gps','Missing readings are not a traffic report');
expect(journeyStatus(stopped,line,'walk',61000).kind==='tracking','A walker standing still does not get a bus incident prompt');
expect(alightingStage('bus',true,500)===1&&alightingStage('bus',true,150)===2,'Notify at 500 m and again near 150 m');
expect(alightingStage('bus',false,50)===0&&alightingStage('walk',true,50)===0,'No alighting alert from an uncertain fix or walking');
let report:RouteReport={id:'test',routeId:'m-xico',routeName:'México',kind:'deviation',reason:'roadworks',startedAt:1000,fixes:[]};
report=appendReportFix(report,off[0],1000);report=appendReportFix(report,off[1],8000);
expect(report.fixes.length===2,'An explicitly started report captures reliable readings');
expect(appendReportFix(report,{...off[2],accuracy:100},17000)===report,'Reports omit imprecise GPS');
const values=new Map<string,string>(),storage={getItem:(key:string)=>values.get(key)??null,setItem:(key:string,value:string)=>{values.set(key,value)}};
setLocalRecordPreference(true,storage);expect(saveRouteReport(report,storage),'Consented local report storage works independently of advertising');
const geo=routeReportGeoJSON({...report,endedAt:17000});
expect(geo.features[0]?.geometry.type==='LineString'&&geo.features[0].properties.verified===false,'Export a proposed GeoJSON trace, never mark it verified');
expect(routeReportGeoJSON({...report,fixes:[...report.fixes,{point:point(5000,200),accuracy:8,time:60000}]}).features.length===2,'A GPS gap must not invent a long straight detour edge');
const sponsor=ads.find(ad=>ad.type==='sponsored_trip') as AdCampaign;
expect(isDeliverableAd(sponsor,new Date('2026-10-12T16:00:00Z'),['m-xico']),'Tacos runs at 09:00 Tepic');
expect(!isDeliverableAd(sponsor,new Date('2026-10-12T23:51:00Z'),['m-xico']),'Tacos must not run at 16:51 when the offer ends at 14:00');
expect(isDeliverableAd(sponsor,new Date('2026-10-13T17:00:00Z'),['m-xico']),'Monday-Friday includes Tuesday');
expect(sponsoredIntroTiming(sponsor.sponsoredTrip).duration===6,'Field sponsor remains visible for six seconds');
expect(sponsoredIntroTiming({...sponsor.sponsoredTrip!,durationSeconds:3}).duration===5,'Legacy short ads get at least five seconds');
expect(meters(origin,point(100))>99,'Simulation uses metres');
console.log('OK: late boarding, GPS recovery/outliers, deviation, stopped vs lost signal, alighting alerts, local reports and ad schedule.');
