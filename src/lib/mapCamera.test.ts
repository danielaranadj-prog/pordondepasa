import {visibleMapPadding,mapFocus,shouldFitTripCamera,sameMapPadding,tripBoundsOptions} from './mapCamera.ts';
const map={top:0,bottom:844,left:0,right:390,width:390,height:844},top={top:20,bottom:130,left:0,right:390,width:390,height:110},panel={top:470,bottom:830,left:10,right:380,width:370,height:360};
const p=visibleMapPadding(map,top,panel),y=(p.top+map.height-p.bottom)/2;
if(y<=top.bottom||y>=panel.top)throw new Error('Position must be visible between panels');
if(visibleMapPadding(map,top,{...panel,top:766,height:64}).bottom>=p.bottom)throw new Error('Collapsed sheet must enlarge visible area');
console.log('OK: visible location between open and collapsed mobile sheets');
const focus=mapFocus(map.width,map.height,p);
if(focus.y!==y||focus.x!==195)throw new Error('Picker tip must match visible map center');
if(shouldFitTripCamera(true,'data')||shouldFitTripCamera(false,'resize'))throw new Error('Exploring and sheet resize must never refit a journey');
if(!shouldFitTripCamera(true,'reset')||!shouldFitTripCamera(false,'data'))throw new Error('Explicit overview and initial results must fit');
const small={...map,height:430,bottom:430},large=visibleMapPadding(small,top,{...panel,top:220,bottom:420});
if(small.height-large.top-large.bottom<119)throw new Error('Keep a usable map viewport on short screens');
console.log('OK: stable exploration, explicit overview and center-pin padding');
const fit=tripBoundsOptions(p);
if(!fit.absolutePadding||fit.padding!==p||fit.duration!==0)throw new Error('Fit must replace existing map padding, not count it twice');
if(!sameMapPadding(p,{...p})||sameMapPadding(p,{...p,bottom:p.bottom+40}))throw new Error('Only actual sheet changes should update map padding');
console.log('OK: long-route bounds and no duplicate panel padding');
const withCredits=visibleMapPadding(map,top,panel,32);
if(map.height-withCredits.bottom+18>panel.top-32-8)throw new Error('Destination marker must remain above the attribution bar');
